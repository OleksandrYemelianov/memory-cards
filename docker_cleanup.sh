#!/bin/bash
# Скрипт для очистки неиспользуемых данных Docker
# ВНИМАНИЕ: Убедитесь, что вам не нужны удаляемые образы или тома

echo "Начало очистки неиспользуемых данных Docker..."

# Удаляем остановленные контейнеры
echo "Удаляем остановленные контейнеры..."
docker container prune -f

# Удаляем неиспользуемые образы
echo "Удаляем неиспользуемые образы..."
docker image prune -a -f

# Удаляем неиспользуемые тома
echo "Удаляем неиспользуемые тома..."
#docker volume prune -f

# Удаляем неиспользуемые сети
echo "Удаляем неиспользуемые сети..."
docker network prune -f

# Очищаем кэш сборки
echo "Очищаем кэш сборки..."
docker builder prune -a -f

# Выводим использование дискового пространства после очистки
echo "Использование дискового пространства после очистки:"
docker system df

# Выводим общее использование дискового пространства после очистки
echo "Общее использование дискового пространства:"
df -h

echo "Очистка завершена."